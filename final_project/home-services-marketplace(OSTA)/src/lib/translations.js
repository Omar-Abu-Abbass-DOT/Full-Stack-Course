/**
 * Translate a free-text content value (category/service title, description, location, etc.)
 * Falls back to the original English text if no translation exists.
 */
export function translateContent(locale, type, value) {
  if (!value || locale !== "ar") return value;
  const dict = {
    category:    CATEGORY_TRANSLATIONS_AR,
    catDesc:     CATEGORY_DESCRIPTIONS_AR,
    serviceTitle:SERVICE_TITLES_AR,
    serviceDesc: SERVICE_DESCRIPTIONS_AR,
    status:      STATUS_TRANSLATIONS_AR,
    role:        ROLE_TRANSLATIONS_AR,
  }[type];
  if (!dict) return value;
  return dict[value] || value;
}

/** Translate a Jordanian city name. */
export function translateLocation(locale, value) {
  if (!value || locale !== "ar") return value;
  const ar = messages.ar[`loc.${value}`];
  return ar || value;
}

export function translate(locale, key, vars) {
  const dict = messages[locale] || messages.en;
  let value = dict[key] || messages.en[key] || key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      value = value.replace(`{${k}}`, v);
    }
  }
  return value;
}
